import { NavigationMenu as NavigationMenuPrimitive } from "@base-ui/react/navigation-menu";
import { cva } from "class-variance-authority";

import { cn } from "#utils";
import { Elevated } from "#lib/elevated";
import { ChevronDownIcon } from "#lib/icons";

// Positioner options pass through so a consumer can, for example, anchor the
// popup to its whole header instead of the open trigger, and portal it into
// that header so the two move as one.
function NavigationMenu({
  align = "start",
  anchor,
  collisionPadding,
  positionMethod,
  positionerClassName,
  popupClassName,
  portalContainer,
  sideOffset,
  className,
  children,
  ...props
}: NavigationMenuPrimitive.Root.Props &
  Pick<
    NavigationMenuPrimitive.Positioner.Props,
    "align" | "anchor" | "collisionPadding" | "positionMethod" | "sideOffset"
  > & {
    popupClassName?: string;
    portalContainer?: NavigationMenuPrimitive.Portal.Props["container"];
    positionerClassName?: string;
  }) {
  return (
    <NavigationMenuPrimitive.Root
      data-slot="navigation-menu"
      className={cn(
        "group/navigation-menu relative flex max-w-max flex-1 items-center justify-center",
        className,
      )}
      {...props}
    >
      {children}
      <NavigationMenuPositioner
        align={align}
        anchor={anchor}
        className={positionerClassName}
        collisionPadding={collisionPadding}
        popupClassName={popupClassName}
        portalContainer={portalContainer}
        positionMethod={positionMethod}
        sideOffset={sideOffset}
      />
    </NavigationMenuPrimitive.Root>
  );
}

